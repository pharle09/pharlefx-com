export type TradingMode = 'manual' | 'copy' | 'bulk';
export type ContractType = 'CALL' | 'PUT';
export type DurationUnit = 't' | 's' | 'm';
export type TradeRequest = { symbol: string; contractType: ContractType; amount: number; duration: number; durationUnit: DurationUnit };
export type BulkTradeRow = TradeRequest & { id: string };
export type CopyTradingSettings = { traderId: string; allocation: number; maxStake: number; maxDailyLoss: number; maxOpenPositions: number };
export type DerivTradeResult = { status: string; requestId?: string; contractId?: string; message?: string };
export type BulkTradeResult = { clientOrderId: string; status: 'accepted' | 'failed' | 'pending'; contractId?: string; message?: string };
export type BulkTradeResponse = { status: 'completed' | 'partial' | 'rejected'; requestId: string; jobId?: string; results: BulkTradeResult[]; message?: string };
export type CopyTradingResponse = { status: 'configured' | 'rejected'; requestId: string; copyId?: string; message: string };
